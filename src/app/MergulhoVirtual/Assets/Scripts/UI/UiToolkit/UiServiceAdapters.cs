    /// <summary>
    /// The species catalog over the AnimalDef ScriptableObjects in
    /// Resources/Animals — the same assets the Animais screen lists, so the beach
    /// species chips, the 3D catalog and (Slice 4) the AR card cannot drift into
    /// three spellings of the same animal.
    ///
    /// <para>Keyed by the asset file name ("lemon_shark"), which is what
    /// beaches_content.json writes. <c>Resources.LoadAll</c> runs once, lazily, on
    /// first use.</para>
    /// </summary>
    public sealed class SpeciesCatalogAdapter : ISpeciesCatalog
    {
        List<SpeciesInfo> species;
        Dictionary<string, SpeciesInfo> byKey;

        public IReadOnlyList<SpeciesInfo> Species
        {
            get
            {
                EnsureLoaded();
                return species;
            }
        }

        public SpeciesInfo Find(string key)
        {
            if (string.IsNullOrEmpty(key)) return null;
            EnsureLoaded();
            return byKey.TryGetValue(key, out var info) ? info : null;
        }

        void EnsureLoaded()
        {
            if (species != null) return;
            species = new List<SpeciesInfo>();
            byKey = new Dictionary<string, SpeciesInfo>(StringComparer.Ordinal);

            foreach (var animal in Resources.LoadAll<AnimalDef>("Animals"))
            {
                if (animal == null || string.IsNullOrEmpty(animal.name)) continue;
                var info = new SpeciesInfo
                {
                    // Asset file name is the key; displayName is the only label.
                    Key = animal.name,
                    DisplayName = string.IsNullOrWhiteSpace(animal.displayName)
                        ? animal.name
                        : animal.displayName,
                    Binomial = animal.binomial,
                    ImageName = animal.imageName,
                    Description = animal.description,
                    // The AR species card's three spec rows (§8.4). Blank on every
                    // shipped asset by design (D8) — the card drops the rows it has
                    // no value for rather than inventing marine biology.
                    ApproximateSize = animal.approximateSize,
                    Diet = animal.diet,
                    Behaviour = animal.behaviour,
                    // Espécie screen (Decision D1). Credits are a licence condition
                    // on every shipped photo and model, not decoration.
                    PhotoCredit = animal.photoCredit,
                    ModelCredit = animal.modelCredit,
                    // The prefab itself is a GameObject and cannot cross into the UI
                    // assembly, so only its PRESENCE does; the model is reached by key
                    // through ISpeciesModelViewer. False here is a real state, and the
                    // usual cause is a dangling reference after the species' FBX was
                    // replaced (CLAUDE.md, "Replacing an existing species' FBX").
                    HasModel = animal.prefab != null,
                    Videos = MapVideos(animal),
                };
                if (byKey.ContainsKey(info.Key))
                {
                    Debug.LogWarning($"[SpeciesCatalog] Duplicate AnimalDef key \"{info.Key}\" — keeping the first.");
                    continue;
                }
                byKey[info.Key] = info;
                species.Add(info);
            }
        }

        /// <summary>
        /// AnimalDef.videos (a global <c>VideoRef[]</c>) to the UI layer's engine-free
        /// mirror. A clip with no URL is dropped rather than carried through to a card
        /// that cannot play — the only honest reading of an empty url field.
        /// </summary>
        static IReadOnlyList<SpeciesVideo> MapVideos(AnimalDef animal)
        {
            if (animal.videos == null || animal.videos.Length == 0) return Array.Empty<SpeciesVideo>();
            var list = new List<SpeciesVideo>(animal.videos.Length);
            foreach (var video in animal.videos)
            {
                if (video == null || string.IsNullOrWhiteSpace(video.url)) continue;
                list.Add(new SpeciesVideo(video.title, video.url));
            }
            return list;
        }
    }

