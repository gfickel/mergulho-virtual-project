    public sealed class ConditionsServiceAdapter : IConditionsService, IDisposable
    {
        readonly ConditionsService service;

        public ConditionsData Current => Map(service != null ? service.CurrentConditions : null);

        /// <summary>No service wired = nothing has failed; the screen then shows the
        /// ordinary "—" rows rather than claiming an error it cannot have had.</summary>
        public bool LastFetchFailed => service != null && service.LastFetchFailed;

        public bool IsFetching => service != null && service.IsFetching;

        public void Refresh() => service?.Refresh();

        public event Action<ConditionsData> Changed;

        public ConditionsServiceAdapter(ConditionsService service)
        {
            this.service = service;
            if (service != null)
            {
                service.ConditionsChanged += OnChanged;
                service.FetchStateChanged += OnFetchStateChanged;
            }
        }

        public void Dispose()
        {
            if (service != null)
            {
                service.ConditionsChanged -= OnChanged;
                service.FetchStateChanged -= OnFetchStateChanged;
            }
        }

        void OnChanged(ConditionsSnapshot snap) => Changed?.Invoke(Map(snap));

        /// <summary>A fetch starting, failing or recovering changes what the card
        /// must draw even though no new snapshot arrived, so it comes out of the
        /// same event — the UI layer has one "re-render" signal, not two.</summary>
        void OnFetchStateChanged() => Changed?.Invoke(Current);

        static ConditionsData Map(ConditionsSnapshot s)
        {
            if (s == null) return null;
            return new ConditionsData
            {
                BeachName = s.beachName,
                FetchedAtUtc = s.fetchedAtTicksUtc > 0 ? s.FetchedAtUtc : DateTime.MinValue,
                WaveHeightM = s.WaveHeightM,
                WavePeriodS = s.WavePeriodS,
                WaveDirectionDeg = s.WaveDirectionDeg,
                SeaTempC = s.SeaTempC,
                WindSpeedKmh = s.WindSpeedKmh,
                WindDirectionDeg = s.WindDirectionDeg,
            };
        }
    }

